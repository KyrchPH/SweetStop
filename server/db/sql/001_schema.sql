create table if not exists public.shifts (
  id uuid primary key default gen_random_uuid(),
  branch_id uuid not null references public.branches(id) on delete restrict,
  opened_by_account_id uuid not null references public.accounts(id) on delete restrict,
  closed_by_account_id uuid references public.accounts(id) on delete set null,
  opening_cash numeric(12, 2) not null default 0 check (opening_cash >= 0),
  closing_cash_expected numeric(12, 2) check (closing_cash_expected >= 0),
  closing_cash_actual numeric(12, 2) check (closing_cash_actual >= 0),
  cash_variance numeric(12, 2),
  status text not null default 'OPEN',
  opened_at timestamptz not null default now(),
  closed_at timestamptz,
  notes text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  check (status in ('OPEN', 'CLOSED')),
  check (
    (status = 'OPEN' and closed_at is null and closed_by_account_id is null and closing_cash_actual is null)
    or
    (
      status = 'CLOSED'
      and closed_at is not null
      and closed_by_account_id is not null
      and closing_cash_expected is not null
      and closing_cash_actual is not null
    )
  )
);

create table if not exists public.sales_receipts (
  id uuid primary key default gen_random_uuid(),
  branch_id uuid not null references public.branches(id) on delete restrict,
  shift_id uuid references public.shifts(id) on delete set null,
  receipt_no text not null,
  cashier_account_id uuid not null references public.accounts(id) on delete restrict,
  promotion_id uuid references public.promotions(id) on delete set null,
  subtotal numeric(12, 2) not null check (subtotal >= 0),
  discount_total numeric(12, 2) not null default 0 check (discount_total >= 0),
  discount_label text,
  total_amount numeric(12, 2) not null check (total_amount >= 0),
  cash_received numeric(12, 2) not null check (cash_received >= 0),
  change_amount numeric(12, 2) not null default 0 check (change_amount >= 0),
  status text not null default 'COMPLETED',
  voided_by_account_id uuid references public.accounts(id) on delete set null,
  voided_at timestamptz,
  void_reason text,
  sold_at timestamptz not null default now(),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (branch_id, receipt_no),
  check (status in ('COMPLETED', 'VOIDED')),
  check (subtotal >= discount_total),
  check (total_amount = subtotal - discount_total),
  check (cash_received >= total_amount),
  check (change_amount = cash_received - total_amount),
  check (
    (status = 'COMPLETED' and voided_at is null and voided_by_account_id is null)
    or
    (status = 'VOIDED' and voided_at is not null and voided_by_account_id is not null)
  )
);

