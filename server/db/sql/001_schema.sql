create or replace view public.branch_variant_availability_v as
select
  c.branch_id,
  c.variant_id,
  p.id as product_id,
  p.name as product_name,
  p.category as product_category,
  v.name as variant_name,
  c.price,
  c.is_applicable,
  c.is_hidden,
  c.manual_unavailable,
  c.unavailable_from,
  c.unavailable_to,
  c.unavailable_reason,
  coalesce(i.on_hand_qty, 0) as on_hand_qty,
  case
    when c.is_applicable = false then 'NOT_APPLICABLE'
    when c.is_hidden = true then 'HIDDEN'
    when c.manual_unavailable = true
      and (c.unavailable_from is null or now() >= c.unavailable_from)
      and (c.unavailable_to is null or now() < c.unavailable_to) then 'UNAVAILABLE'
    when coalesce(i.on_hand_qty, 0) <= 0 then 'OUT_OF_STOCK'
    else 'AVAILABLE'
  end as availability_status,
  case
    when c.is_applicable = true
      and c.is_hidden = false
      and not (
        c.manual_unavailable = true
        and (c.unavailable_from is null or now() >= c.unavailable_from)
        and (c.unavailable_to is null or now() < c.unavailable_to)
      )
      and coalesce(i.on_hand_qty, 0) > 0 then true
    else false
  end as is_sellable
from public.branch_variant_config c
join public.product_variants v on v.id = c.variant_id
join public.products p on p.id = v.product_id
left join public.branch_variant_inventory i
  on i.branch_id = c.branch_id
  and i.variant_id = c.variant_id;
